import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {sourceReport,combineReports} from './batch.mjs';
import {buildConclusion,clientExportModel} from './report-narrative.mjs';
import {CASES} from './analyzer.mjs';
import {makeDocx} from './exporter.mjs';
import {printReport} from './print.mjs';
const require=createRequire(import.meta.url);
globalThis.JSZip=require('./vendor/jszip.min.js');
const cover='DAILY REPORT\nExample Bank\nReporting Period\nFrom 10/17/2026 12:00:00 AM\nTo 10/18/2026 12:00:00 AM';
const sections=CASES.map(c=>c+'\n'+(c==='Third Party VPN'?'1 10.1.1.1 10.1.1.2 success tunnel role 5':'No Relevant Data'));
const report=(pages,name='one.pdf',id='R1')=>sourceReport([cover,...pages],name,id);
const clean=combineReports([report(sections)]);
assert.equal(clean.total,5);
assert.match(clean.conclusion,/no suspicious activity was identified within the reported monitoring categories/);
assert.doesNotMatch(clean.summary+clean.conclusion,/parsed|extraction|chunks|source index/i);
const incomplete=combineReports([report(['SSH Connections CP\n1 10.1.1.1 10.1.1.2 Accept 20'])]);
assert.match(incomplete.conclusion,/^Further validation/);
const suspicious=combineReports([report(sections.map(p=>p.startsWith('Suspicious Connection Internal to External')?'Suspicious Connection Internal to External\n1 10.1.1.1 203.0.113.1 Accept 2':p))]);
assert.match(suspicious.conclusion,/^Further investigation/);
const overlap=combineReports([report(sections),report(sections,'two.pdf','R2')]);
assert.equal(overlap.total,10);assert.match(overlap.conclusion,/^Further validation/);
assert.match(buildConclusion({...clean,findings:[{severity:'INFO',title:'VPN status is unspecified',action:'Review VPN status.'}]}),/^Further validation/);
const snapshot=JSON.stringify(suspicious),exported=clientExportModel(suspicious);
assert.equal(JSON.stringify(suspicious),snapshot);
assert.doesNotMatch(exported.findings.map(f=>f.evidence).join(' '),/parsed|PDF pages/);
for(const chartType of ['pie','bar']){
 const zip=await JSZip.loadAsync(await makeDocx(suspicious,{chartType}));
 const xml=await zip.file('word/document.xml').async('text');
 assert.ok(zip.file('word/charts/chart1.xml'));assert.ok(zip.file('word/embeddings/data1.xlsx'));
 assert.match(xml,/Further investigation/);
 assert.doesNotMatch(xml,/parsed|extraction|chunks|Source index|Edit Data|PDF page references|>ROWS</i);
}
let html='';
globalThis.window={open:()=>({document:{write:s=>{html=s;},close(){},getElementById:()=>({})},focus(){}})};
printReport(incomplete,[],incomplete.conclusion);
assert.match(html,/Assessment Scope and Limitations/);
assert.doesNotMatch(html,/parsed|extraction|chunks|Source index|<th>Rows|PDF pages/i);
console.log('PASS expanded narratives, scoped verdicts, suspicious/incomplete/overlapping cases, unchanged totals, editable pie/bar DOCX and client-facing print output.');
